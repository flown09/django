% Границы интегрирования
a = 0; b = 3;
N = 1000; % Количество случайных точек
% Определяем функцию
y = @(x) sqrt(1 + cos(x).^2);
% Генерация точек
Xrand = a + (b - a) * rand(N, 1);
Ymax = max(y(linspace(a, b, N)));
Yrand = Ymax * rand(N, 1);
% Подсчет точек под графиком
n = sum(Yrand <= y(Xrand));
%Вычисление интеграла методом Монте-Карло
S = (b - a) * Ymax;
Fmk = S * (n / N);
% Альтернативный метод Монте-Карло (суммирование)
Fmk2 = (b - a) * mean(y(Xrand));
% Вывод результатов
fprintf('Метод Монте-Карло (попадание точек): %.6f\n', Fmk);
fprintf('Метод Монте-Карло (усреднение значений): %.6f\n', Fmk2);