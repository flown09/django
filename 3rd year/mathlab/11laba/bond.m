% Задание параметров
f = @(x) x.^2 .* exp(-2*x);
a = 0;
b = 1.6;
h = (b - a) / 100;
x = a:h:b;
y = feval(f, x); % значения функции
% Метод правых прямоугольников
y_right = y(2:end); % без первого значения
Fr = sum(h * y_right);
disp('Метод правых прямоугольников:');
disp(Fr);
% Метод левых прямоугольников
y_left = y(1:end-1); % без последнего значения
Fl = sum(h * y_left);
disp('Метод левых прямоугольников:');
disp(Fl);
% Метод средних прямоугольников
x_mid = a + h/2 : h : b - h/2;
y_mid = feval(f, x_mid);
Fm = sum(h * y_mid);
disp('Метод средних прямоугольников:');
disp(Fm);
% Метод трапеций
Ft = trapz(x, y);
disp('Метод трапеций (trapz):');
disp(Ft);
% Метод Симпсона (quad)
Fq = quad(@(x) x.^2 .* exp(-2*x), a, b, 1e-6);
disp('Метод Симпсона (quad):');
disp(Fq);
% Символьное интегрирование
syms x_sym
I = int(x_sym^2 * exp(-2*x_sym), x_sym, a, b);
disp('Символьное интегрирование:');
disp(double(I));
